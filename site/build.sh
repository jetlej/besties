#!/bin/bash
#
# Builds the deployable site from src/ templates.
# The product name lives HERE and nowhere else — change it once, rebuild,
# and every page, meta tag, and FAQ answer follows.
#
# Usage:  ./build.sh   (then `vercel deploy --prod` to ship)

set -euo pipefail
cd "$(dirname "$0")"

APP_NAME="Besties"
# Besties AI prices as shown on the site. Must match the Stripe prices behind
# STRIPE_PRICE_MONTHLY / STRIPE_PRICE_YEARLY (Stripe is what actually charges)
# and the paywall copy in SubscriptionViews.swift.
AI_PRICE_MONTHLY='$7/mo'
AI_PRICE_YEARLY='$69/yr'

# index.html = head wrapper + templated landing page body
{
cat <<HEAD
<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${APP_NAME} — a time machine for your messages</title>
<meta name="description" content="${APP_NAME} turns your iMessage and WhatsApp history into a timeline you can travel. Scrub to any month of your life, see who you were closest to, and drop into the exact conversation. Free, and your history stays on your Mac.">
<meta property="og:title" content="${APP_NAME} — a time machine for your messages">
<meta property="og:description" content="Scrub back through years of iMessage and WhatsApp. See who mattered, jump to any moment, read it like it was. Entirely on-device.">
<meta property="og:image" content="https://besties.gg/og.png">
<meta property="og:image:width" content="1200">
<meta property="og:image:height" content="630">
<meta property="og:image:type" content="image/png">
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:title" content="${APP_NAME} — a time machine for your messages">
<meta name="twitter:description" content="Scrub back through years of iMessage and WhatsApp. See who mattered, jump to any moment, read it like it was. Entirely on-device.">
<meta name="twitter:image" content="https://besties.gg/og.png">
<meta name="color-scheme" content="light">
<link rel="icon" type="image/png" href="/icon.png">
<link rel="apple-touch-icon" href="/icon.png">
<script>window.bt={q:[],track:function(e,p){window.bt.q.push([e,p])}}</script>
<script defer src="/t.js"></script>
</head>
<body>
HEAD
sed -e "s/__APP_NAME__/${APP_NAME}/g" -e "s|__AI_PRICE_MONTHLY__|${AI_PRICE_MONTHLY}|g" -e "s|__AI_PRICE_YEARLY__|${AI_PRICE_YEARLY}|g" -e '/^<title>/d' src/landing.html
printf '</body>\n</html>\n'
} > index.html

# thanks.html (download + install steps) and subscribed.html (after Stripe
# Checkout) are complete pages; just substitute the name
for page in thanks subscribed; do
  sed "s/__APP_NAME__/${APP_NAME}/g" "src/${page}.html" > "${page}.html"
done

# The API functions (emails) need the name too
printf '// Generated by build.sh from APP_NAME. Do not edit.\nmodule.exports = "%s";\n' "${APP_NAME}" > api/_lib/app-name.js

echo "✅ Built index.html + thanks.html + subscribed.html as ${APP_NAME}"
